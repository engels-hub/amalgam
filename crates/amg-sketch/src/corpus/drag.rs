//! Scripted-drag fixtures and harness (SK-05): the 200-entity generated sketch, script
//! resampling, and a runner that drives a [`NativeSolver`] drag session through a script and
//! reports the SK-05 metrics (per-frame time, jitter, branch flips, convergence).
//!
//! Jitter is the SK-13 metric (note §5.3): `max_k max_{p not dragged} ‖p_k − p_{k−1}‖ /
//! ‖c_k − c_{k−1}‖` over point entities; flips use the sign of `cross(a − o1, b − o1)` of
//! cases with points named `o1`, `a`, `b` (D7), ignoring frames at the toggle (`|sin| <` [`TOGGLE_SIN`]).

use std::time::Instant;

use amg_core::Point2;

use super::{
    Case, CaseEntity, CaseGeom, CaseSource, CaseStatus, DEFAULT_SOLUTION_TOL, DragScript, Expected,
    FORMAT_VERSION, SourceSet,
};
use crate::ids::EntityId;
use crate::model::{ConstraintKind, Dimension, DimensionKind, Sketch};
use crate::solve::{
    DragMode, DragSession, DragSpec, DragStats, NativeSolver, SolveOptions, SolverBackend,
};

/// Frames with `|sin|` below this are at the toggle: the residual tolerance (1e-10 mm) leaves
/// `|sin|` up to about 1e-5 undetermined there, so its sign is numerical noise.
const TOGGLE_SIN: f64 = 1e-4;

/// Triangles of the generated chain.
const CHAIN_TRIANGLES: usize = 40;

/// A generated 201-entity sketch: a chain of 40 rigid triangles (three length dimensions each),
/// every triangle hinged to the next at a shared vertex, laid out as an accordion. The first
/// triangle is pinned (two fixed points), so the 39 hinges are free: DOF 39, every drag is a
/// nonlinear many-DOF problem with a minimum-norm answer. The drag script moves the last vertex
/// over `frames` frames along a Lissajous-like curve inside the chain's reach.
pub fn truss_case(frames: usize) -> Case {
    let n = CHAIN_TRIANGLES;
    let mut entities = Vec::new();
    let mut pos: Vec<[f64; 2]> = Vec::new();
    let mut add_point = |entities: &mut Vec<CaseEntity>, p: [f64; 2]| {
        entities.push(CaseEntity {
            name: String::new(),
            geom: CaseGeom::Point { at: p },
            construction: false,
        });
        pos.push(p);
        u32::try_from(entities.len() - 1).unwrap_or(0)
    };
    // Pivots p_0..p_n along a zigzag, apexes q_j above each baseline.
    let pivots: Vec<[f64; 2]> = (0..=n)
        .map(|j| [9.0 * j as f64, if j % 2 == 0 { 0.0 } else { 6.0 }])
        .collect();
    let (mut p_ids, mut q_ids) = (Vec::new(), Vec::new());
    p_ids.push(add_point(&mut entities, pivots[0]));
    for j in 0..n {
        let (a, b) = (pivots[j], pivots[j + 1]);
        let (mx, my) = ((a[0] + b[0]) / 2.0, (a[1] + b[1]) / 2.0);
        let (dx, dy) = (b[0] - a[0], b[1] - a[1]);
        let len = dx.hypot(dy);
        let apex = [mx - dy / len * 7.0, my + dx / len * 7.0];
        q_ids.push(add_point(&mut entities, apex));
        p_ids.push(add_point(&mut entities, b));
    }
    let at = |entities_pos: &[[f64; 2]], p: u32| entities_pos[p as usize];
    let mut constraints = vec![
        ConstraintKind::Fix {
            entity: EntityId(p_ids[0]),
        },
        ConstraintKind::Fix {
            entity: EntityId(q_ids[0]),
        },
    ];
    for j in 0..n {
        for (a, b) in [
            (p_ids[j], q_ids[j]),
            (q_ids[j], p_ids[j + 1]),
            (p_ids[j], p_ids[j + 1]),
        ] {
            entities.push(CaseEntity {
                name: String::new(),
                geom: CaseGeom::Line { start: a, end: b },
                construction: false,
            });
            let line = EntityId(u32::try_from(entities.len() - 1).unwrap_or(0));
            // The pinned triangle's apex edge is fixed by its two fixed points.
            if j == 0 && a == p_ids[0] && b == q_ids[0] {
                continue;
            }
            let (p, q) = (at(&pos, a), at(&pos, b));
            constraints.push(ConstraintKind::Dimension(Dimension {
                kind: DimensionKind::Length { line },
                value: (p[0] - q[0]).hypot(p[1] - q[1]),
                driving: true,
                label_pos: Point2::ZERO,
            }));
        }
    }
    let tip = p_ids[n];
    let [tx, ty] = at(&pos, tip);
    let path = (0..frames)
        .map(|k| {
            let s = k as f64 / (frames.max(2) - 1) as f64;
            let a = std::f64::consts::TAU;
            [
                round12(tx - 20.0 * (1.0 - (a * 2.0 * s).cos()) / 2.0),
                round12(ty + 25.0 * (a * 3.0 * s).sin()),
            ]
        })
        .collect();
    Case {
        format: FORMAT_VERSION,
        id: "own/drag_chain200".to_string(),
        source: CaseSource {
            set: SourceSet::Own,
            origin: "generated by amg_sketch::corpus::drag::truss_case".to_string(),
            licence: "MIT OR Apache-2.0".to_string(),
        },
        description: "Chain of 40 hinged rigid triangles (SK-05 200-entity drag).".to_string(),
        tags: vec!["drag".to_string(), "generated".to_string()],
        entities,
        constraints,
        expected: Expected {
            status: CaseStatus::Converged,
            also_accept: Vec::new(),
            dof: Some(u32::try_from(n - 1).unwrap_or(0)),
            solution: None,
            tolerance: DEFAULT_SOLUTION_TOL,
            groups: Vec::new(),
        },
        drag: Some(DragScript { entity: tip, path }),
    }
}

fn round12(v: f64) -> f64 {
    (v * 1e12).round() / 1e12
}

/// `frames` cursor positions along the polyline `path` (linear in the path parameter).
pub fn resample(path: &[[f64; 2]], frames: usize) -> Vec<[f64; 2]> {
    if path.len() < 2 || frames < 2 {
        return path.to_vec();
    }
    (0..frames)
        .map(|k| {
            let s = k as f64 / (frames - 1) as f64 * (path.len() - 1) as f64;
            let i = (s.floor() as usize).min(path.len() - 2);
            let t = s - i as f64;
            [
                path[i][0] + t * (path[i + 1][0] - path[i][0]),
                path[i][1] + t * (path[i + 1][1] - path[i][1]),
            ]
        })
        .collect()
}

/// Metrics of one scripted drag.
#[derive(Clone, Debug)]
pub struct DragRun {
    /// Frames driven.
    pub frames: usize,
    /// `DragSession::step` time per frame, µs.
    pub times_us: Vec<f64>,
    /// SK-13 jitter (see the module docs).
    pub jitter: f64,
    /// Branch flips (`None` without `o1`/`a`/`b` points).
    pub flips: Option<u32>,
    /// Frame indices at which the branch flipped.
    pub flip_frames: Vec<usize>,
    /// Frames whose step reported a converged status.
    pub converged_frames: usize,
    /// Largest residual over the frames.
    pub max_residual: f64,
    /// Session counters.
    pub stats: DragStats,
}

impl DragRun {
    /// 95th percentile of the frame time, µs.
    pub fn p95_us(&self) -> f64 {
        self.quantile_us(0.95)
    }

    /// Median frame time, µs.
    pub fn median_us(&self) -> f64 {
        self.quantile_us(0.5)
    }

    fn quantile_us(&self, q: f64) -> f64 {
        let mut v = self.times_us.clone();
        v.sort_by(f64::total_cmp);
        v.get(((v.len().max(1) - 1) as f64 * q).round() as usize)
            .copied()
            .unwrap_or(0.0)
    }
}

/// Drives a drag of `case.drag.entity` through `path` (default: the case's own script) with a
/// fresh [`NativeSolver`] in `mode`. The sketch is solved first. `None` if the case has no
/// drag entity or the session cannot start.
pub fn run_script(case: &Case, path: Option<&[[f64; 2]]>, mode: DragMode) -> Option<DragRun> {
    let script = case.drag.as_ref()?;
    let path = path.unwrap_or(&script.path);
    let mut built = case.build().ok()?;
    let mut solver = NativeSolver::new().with_drag_mode(mode);
    solver.solve(&mut built.sketch, &SolveOptions::default(), &|| false);
    let grabbed = built.entities[script.entity as usize];
    let points: Vec<EntityId> = case
        .entities
        .iter()
        .enumerate()
        .filter(|(_, e)| matches!(e.geom, CaseGeom::Point { .. }))
        .map(|(i, _)| built.entities[i])
        .collect();
    let branch = ["o1", "a", "b"].map(|name| {
        case.entities
            .iter()
            .position(|e| e.name == name)
            .map(|i| built.entities[i])
    });
    let snapshot = |s: &Sketch| -> Vec<Point2> {
        points
            .iter()
            .map(|&id| s.point(id).unwrap_or(Point2::ZERO))
            .collect()
    };
    let side = |s: &Sketch| -> Option<f64> {
        let [o, a, b] = branch;
        let (o, a, b) = (s.point(o?)?, s.point(a?)?, s.point(b?)?);
        let (u, w) = (a - o, b - o);
        let sin = (u.x * w.y - u.y * w.x) / (u.length() * w.length());
        (sin.abs() >= TOGGLE_SIN).then_some(sin)
    };
    let sketch = &mut built.sketch;
    let grab = sketch.point(grabbed)?;
    let mut session = solver
        .drag(
            sketch,
            DragSpec {
                entity: grabbed,
                grab,
            },
        )
        .ok()?;
    let mut run = DragRun {
        frames: path.len(),
        times_us: Vec::with_capacity(path.len()),
        jitter: 0.0,
        flips: branch.iter().all(Option::is_some).then_some(0),
        flip_frames: Vec::new(),
        converged_frames: 0,
        max_residual: 0.0,
        stats: DragStats::default(),
    };
    let mut prev = snapshot(sketch);
    let mut prev_cursor = grab;
    let mut prev_side = side(sketch);
    let grabbed_slot = points.iter().position(|&id| id == grabbed);
    for (frame, &t) in path.iter().enumerate() {
        let target = Point2::new(t[0], t[1]);
        let t0 = Instant::now();
        let st = session.step(sketch, target, &|| false);
        run.times_us.push(t0.elapsed().as_secs_f64() * 1e6);
        run.converged_frames += usize::from(st.status.is_converged());
        run.max_residual = run.max_residual.max(st.max_residual);
        let now = snapshot(sketch);
        let step = target.distance(prev_cursor);
        if step > 0.0 {
            for (i, (p, q)) in now.iter().zip(&prev).enumerate() {
                if Some(i) != grabbed_slot {
                    run.jitter = run.jitter.max(p.distance(*q) / step);
                }
            }
        }
        let s = side(sketch);
        if let (Some(a), Some(b), Some(f)) = (prev_side, s, run.flips.as_mut())
            && a * b < 0.0
        {
            *f += 1;
            run.flip_frames.push(frame);
        }
        prev_side = s.or(prev_side);
        prev_cursor = target;
        prev = now;
    }
    run.stats = session.stats();
    Some(run)
}

/// Drives a boxed session through cursor positions and returns every step's result.
pub fn drive(
    session: &mut dyn DragSession,
    sketch: &mut Sketch,
    path: &[Point2],
) -> Vec<crate::solve::DragStep> {
    path.iter()
        .map(|&t| session.step(sketch, t, &|| false))
        .collect()
}
